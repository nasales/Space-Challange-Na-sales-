"""Cross-dataset check of the featured cases (Ivan): Perry's series vs NASA POWER.

Usage:
    python -m pipeline.cross_check [--write]

For each featured case file in data/cache/ (T2M, PRECIP, SOILM, from Perry's case export) with a POWER
raw file of the same variable type in data/raw/power/ (T2M, PRECTOTCORR, GWETTOP), both series are cut
to their common period and analyze_trend is run on each. The table compares slope sign (direction),
significance and slope ratio (case / POWER).
SOILM (GLDAS kg/m² in the top 10 cm) and GWETTOP (POWER surface wetness, fraction 0-1) are different
quantities: only the direction is compared, not significance or ratio.
With --write the paragraph and table go into docs/methods.md between the CROSS_START / CROSS_END
markers (added before the results section if missing).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from pipeline import nasa_power
from pipeline.build_cases import CACHE_DIR, RAW_DIR, ROOT, load_case_file
from pipeline.cases import CASES, POWER_PARAMS
from pipeline.trend import analyze_trend

METHODS_PATH = ROOT / "docs" / "methods.md"
START = "<!-- CROSS_START (generated by python -m pipeline.cross_check --write) -->"
END = "<!-- CROSS_END -->"
DIRECTION_ONLY = {"SOILM"}  # different quantity in POWER (GWETTOP)


def _clip(dates: list[str], values: list, first: str, last: str) -> tuple[list[str], list]:
    keep = [i for i, d in enumerate(dates) if first <= d <= last]
    return [dates[i] for i in keep], [values[i] for i in keep]


def _sign(slope: float) -> str:
    return "up" if slope > 0 else "down" if slope < 0 else "flat"


def compare(cases: list[dict] = CASES, cache_dir: Path = CACHE_DIR, raw_dir: Path = RAW_DIR) -> list[dict]:
    """One row per case series with a POWER counterpart; trends over the common period of both."""
    rows = []
    for case in cases:
        for variable, param in POWER_PARAMS.items():
            case_path = Path(cache_dir) / f"case_{case['id']}_{variable}.json"
            raw_path = Path(raw_dir) / f"{case['id']}_{param}.json"
            if variable == param and case_path.exists():
                # T2M keeps its name in both sources: only a case file built from the export counts.
                if json.loads(case_path.read_text(encoding="utf-8"))["dataset"].startswith("NASA POWER"):
                    continue
            if not case_path.exists() or not raw_path.exists():
                continue
            _, series = load_case_file(case_path)
            p_dates, p_values, _ = nasa_power.parse(json.loads(raw_path.read_text(encoding="utf-8")), param)
            first = max(series.dates[0], p_dates[0])
            last = min(series.dates[-1], p_dates[-1])
            c_trend = analyze_trend(*_clip(series.dates, series.values, first, last))
            p_trend = analyze_trend(*_clip(p_dates, p_values, first, last))
            direction_only = variable in DIRECTION_ONLY
            rows.append({
                "case": case["title"], "variable": variable, "power_param": param,
                "period": f"{first} to {last}",
                "case_slope": c_trend["slope"], "power_slope": p_trend["slope"],
                "case_sig": bool(c_trend["significant"]), "power_sig": bool(p_trend["significant"]),
                "same_direction": _sign(c_trend["slope"]) == _sign(p_trend["slope"]),
                "same_significance": None if direction_only else c_trend["significant"] == p_trend["significant"],
                "ratio": None if direction_only or p_trend["slope"] == 0 else c_trend["slope"] / p_trend["slope"],
            })
    return rows


def summary(rows: list[dict]) -> dict:
    sig = [r for r in rows if r["same_significance"] is not None]
    return {"n": len(rows), "direction": sum(r["same_direction"] for r in rows),
            "n_sig": len(sig), "significance": sum(r["same_significance"] for r in sig)}


def _yn(x: bool) -> str:
    return "yes" if x else "no"


def table(rows: list[dict]) -> str:
    lines = [
        "| Case | Variable (case / POWER) | Common period | Direction (case / POWER) | Significant (case / POWER) | Slope ratio case / POWER | Agree |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        agree = "direction" if r["same_direction"] else "no"
        if r["same_significance"] is not None:
            agree = ("direction + significance" if r["same_significance"] else "direction only") \
                if r["same_direction"] else ("significance only" if r["same_significance"] else "no")
        ratio = "n/a (different quantity)" if r["variable"] in DIRECTION_ONLY else (
            "n/a" if r["ratio"] is None else f"{r['ratio']:.2f}")
        lines.append(
            f"| {r['case']} | {r['variable']} / {r['power_param']} | {r['period']} "
            f"| {_sign(r['case_slope'])} / {_sign(r['power_slope'])} "
            f"| {_yn(r['case_sig'])} / {_yn(r['power_sig'])} | {ratio} | {agree} |"
        )
    return "\n".join(lines)


def without_power(rows: list[dict], cases: list[dict] = CASES, cache_dir: Path = CACHE_DIR) -> list[str]:
    """Case series built from the export that have no POWER counterpart in the comparison."""
    done = {(r["case"], r["variable"]) for r in rows}
    out = []
    for case in cases:
        for variable in POWER_PARAMS:
            path = Path(cache_dir) / f"case_{case['id']}_{variable}.json"
            if path.exists() and (case["title"], variable) not in done and                     not json.loads(path.read_text(encoding="utf-8"))["dataset"].startswith("NASA POWER"):
                out.append(f"{case['title']} {variable}")
    return out


def section(rows: list[dict], missing: list[str] | None = None) -> str:
    s = summary(rows)
    missing = without_power(rows) if missing is None else missing
    text = (
        "Each featured series (Perry's native-pixel MERRA-2 / GPM IMERG / GLDAS data) is compared with "
        "NASA POWER at the same point, both cut to their common period and analysed with the same "
        "`analyze_trend`. Soil moisture is compared by direction only, because GLDAS 0-10 cm soil "
        "moisture (kg/m²) and POWER `GWETTOP` (surface wetness, 0-1) are different quantities. "
        f"Direction agrees in {s['direction']} of {s['n']} series; significance agrees in "
        f"{s['significance']} of {s['n_sig']} temperature and precipitation series. "
        "POWER temperature is itself based on MERRA-2, so the T2M agreement (slope ratio close to 1) "
        "is a consistency check, not an independent confirmation; precipitation and soil moisture "
        "come from different products and are the informative comparisons."
    )
    if missing:
        text += f" Not compared (no POWER file): {', '.join(missing)}."
    return f"{text}\n\n{table(rows)}"


def replace_section(doc: str, body: str) -> str:
    """Put `body` between the CROSS markers; add the block before the results section if missing."""
    block = f"{START}\n{body}\n{END}"
    if START in doc and END in doc:
        head, rest = doc.split(START, 1)
        return head + block + rest.split(END, 1)[1]
    anchor = "## Results of the featured cases"
    new = f"## Cross-dataset check\n{block}\n\n"
    return doc.replace(anchor, new + anchor, 1) if anchor in doc else doc.rstrip("\n") + "\n\n" + new


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Cross-dataset check: featured cases vs NASA POWER.")
    ap.add_argument("--write", action="store_true", help="write the section into docs/methods.md")
    args = ap.parse_args(argv)
    rows = compare()
    body = section(rows)
    sys.stdout.reconfigure(encoding="utf-8")
    print(body)
    if args.write:
        doc = METHODS_PATH.read_text(encoding="utf-8")
        METHODS_PATH.write_text(replace_section(doc, body), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
