"""Results table of the featured cases, regenerated from data/cache/case_*.json.

Usage:
    python -m pipeline.results_table            # print the Markdown table
    python -m pipeline.results_table --write    # also replace the table in docs/methods.md

In docs/methods.md the table sits between the markers RESULTS_START and RESULTS_END.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from pipeline.build_cases import ROOT, case_file, load_case_file
from pipeline.cases import CASES

METHODS_PATH = ROOT / "docs" / "methods.md"
START = "<!-- RESULTS_START (generated by python -m pipeline.results_table --write) -->"
END = "<!-- RESULTS_END -->"


def _num(x: float) -> str:
    return f"{x:+.3g}"


def results_table(cases: list[dict] = CASES, root: Path = ROOT) -> str:
    """Markdown table: case, variable, slope per decade with units, 95% CI, p, significant."""
    lines = [
        "| Case | Variable | Slope per decade | 95% CI per decade | p | Significant |",
        "|---|---|---|---|---|---|",
    ]
    for case in cases:
        for var in case["variables"]:
            trend, series = load_case_file(Path(root) / case_file(case["id"], var))
            p = trend["p_value"]
            lines.append(
                f"| {case['title']} | {var} | {_num(trend['slope'] * 10)} {series.units} "
                f"| {_num(trend['slope_ci_low'] * 10)} to {_num(trend['slope_ci_high'] * 10)} "
                f"| {'< 0.001' if p < 0.001 else f'{p:.3f}'} | {'yes' if trend['significant'] else 'no'} |"
            )
    return "\n".join(lines)


def replace_table(text: str, table: str) -> str:
    """Put `table` between the START and END markers of `text`."""
    if START not in text or END not in text:
        raise ValueError("docs/methods.md is missing the RESULTS_START / RESULTS_END markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{table}\n{END}{tail}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Results table of the featured cases.")
    ap.add_argument("--write", action="store_true", help="replace the table in docs/methods.md")
    args = ap.parse_args(argv)

    table = results_table()
    sys.stdout.reconfigure(encoding="utf-8")
    print(table)
    if args.write:
        text = METHODS_PATH.read_text(encoding="utf-8")
        METHODS_PATH.write_text(replace_table(text, table), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
