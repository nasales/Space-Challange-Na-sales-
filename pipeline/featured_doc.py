"""List of the featured cases for docs/featured_cases.md, generated from data/cases_index.json and the case files.

Usage:
    python -m pipeline.featured_doc [--write]

With --write the list replaces the text between the CASES_START / CASES_END markers of
docs/featured_cases.md. It is also refreshed by pipeline.build_cases.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from pipeline.build_cases import INDEX_PATH, ROOT, load_case_file
from pipeline.explain import WEAK

DOC_PATH = ROOT / "docs" / "featured_cases.md"
START = "<!-- CASES_START (generated by python -m pipeline.featured_doc --write) -->"
END = "<!-- CASES_END -->"
NAMES = {"T2M": "temperature", "PRECIP": "precipitation", "SOILM": "soil moisture (0-10 cm)",
         "PRECTOTCORR": "precipitation (POWER)", "GWETTOP": "soil wetness (POWER)",
         "NDVI": "vegetation (NDVI)", "LST": "land surface temperature", "SNOW": "snow cover"}


def _result(path: Path, facts: str) -> str:
    trend, series = load_case_file(path)
    name = NAMES.get(series.variable, series.variable)
    slope = f"{trend['slope'] * 10 + 0.0:+.3g} {series.units} per decade"
    if not trend["significant"]:
        return f"{name}: {slope}, not significant (p = {trend['p_value']:.2f})"
    weak = ", weak evidence" if WEAK in facts else ""
    p = "p < 0.001" if trend["p_value"] < 0.001 else f"p = {trend['p_value']:.3f}"
    return f"{name}: {slope}, significant ({p}{weak})"


def cases_list(index_path: Path = INDEX_PATH, root: Path = ROOT) -> str:
    index = json.loads(Path(index_path).read_text(encoding="utf-8"))
    lines = []
    for i, case in enumerate(index, 1):
        lines.append(f"{i}. **{case['title']}** (`{case['id']}`, {case['place']}, {case['lat']}, {case['lon']})")
        for f in case["files"]:
            var = f.rsplit("_", 1)[1][:-5]
            lines.append(f"   - {_result(Path(root) / f, case['facts'].get(var, ''))}")
    return "\n".join(lines)


def replace_block(doc: str, body: str) -> str:
    if START not in doc or END not in doc:
        raise ValueError("docs/featured_cases.md is missing the CASES_START / CASES_END markers")
    head, rest = doc.split(START, 1)
    return f"{head}{START}\n{body}\n{END}{rest.split(END, 1)[1]}"


def write_doc(path: Path = DOC_PATH) -> None:
    path = Path(path)
    path.write_text(replace_block(path.read_text(encoding="utf-8"), cases_list()), encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Featured cases list for docs/featured_cases.md.")
    ap.add_argument("--write", action="store_true", help="replace the list in docs/featured_cases.md")
    args = ap.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8")
    print(cases_list())
    if args.write:
        write_doc()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
